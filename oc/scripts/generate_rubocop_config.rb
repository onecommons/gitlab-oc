#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes oc/rubocop/rubocop-oc.yml: every Include/Exclude entry upstream scopes
# to ee/ or jh/ gets an oc/ twin, so oc/ is linted like the rest of the tree.
# .rubocop.yml inherits the file through its oc/rubocop/**/*.yml glob and
# merges Include/Exclude lists. Rerun after an upstream bump.
#
#   ruby oc/scripts/generate_rubocop_config.rb

require 'yaml'

module GenerateRubocopConfig
  ROOT = File.expand_path('../..', __dir__)
  SOURCES = ['.rubocop.yml', *Dir.glob('rubocop/rubocop-*.yml', base: ROOT)].freeze
  OUTPUT = 'oc/rubocop/rubocop-oc.yml'
  HEADER = <<~HEADER
    # Generated by oc/scripts/generate_rubocop_config.rb. Do not edit by hand.
    #
    # Mirrors every ee/ and jh/ Include/Exclude entry in .rubocop.yml and
    # rubocop/*.yml for oc/, so oc/ is linted like the rest of the tree.
  HEADER

  # EE-specific by nature, or not applicable to code that never loads EE.
  # EeOnlyClass keeps classes out of ee/**/ee, but oc/**/oc is where all of
  # the fork's code lives, classes included.
  SKIPPED_COPS = %w[
    Gitlab/EeOnlyClass
    Gitlab/RSpec/AvoidSetup
    Gitlab/RSpec/MisplacedEeSpecFile
    Gitlab/SaasFeatureAvailableOutsideEe
  ].freeze

  # oc/scripts mirrors upstream's scripts/, which is excluded outright.
  EXTRA = { 'Naming/FileName' => { 'Exclude' => ['oc/scripts/**/*'] } }.freeze

  COP_LINE = %r{\A([A-Z][\w/]*):\s*\z}
  LIST_LINE = /\A  (Include|Exclude):\s*\z/
  ENTRY_LINE = /\A\s+- '?([^'#\s]+)'?/
  EDITION_PATTERN = %r{\A(?:\{,ee/,(?:jh|qa)/\}|ee/(?=.*\*\*))(.*)\z}

  def self.oc_pattern(pattern)
    match = EDITION_PATTERN.match(pattern)
    return unless match

    rest = match[1]
    return if rest.match?(%r{\bjh/}) || rest.include?('(')

    # An inner ee/ is the extension-module tree (ee/lib/ee/api); ours is oc/lib/oc/api.
    "oc/#{rest.gsub(%r{\bee/}, 'oc/')}"
  end

  def self.collect
    entries = Hash.new { |hash, key| hash[key] = Hash.new { |inner, list| inner[list] = [] } }

    SOURCES.each do |source|
      cop = nil
      list = nil

      File.foreach(File.join(ROOT, source)) do |line|
        cop_match = COP_LINE.match(line)
        list_match = LIST_LINE.match(line)

        if cop_match
          cop = cop_match[1]
          list = nil
        elsif list_match
          list = list_match[1]
        elsif line.match?(/\A  \w/)
          list = nil
        elsif cop && list && !skipped?(cop)
          entry = ENTRY_LINE.match(line)
          oc = entry && oc_pattern(entry[1])
          entries[cop][list] << oc if oc
        end
      end
    end

    EXTRA.each { |cop, lists| lists.each { |list, patterns| entries[cop][list].concat(patterns) } }
    entries
  end

  def self.skipped?(cop)
    cop.start_with?('Search/') || SKIPPED_COPS.include?(cop)
  end

  def self.run
    output = collect.sort.to_h.transform_values do |lists|
      lists.sort.to_h.transform_values { |patterns| patterns.uniq.sort }
    end

    File.write(File.join(ROOT, OUTPUT), HEADER + YAML.dump(output).delete_prefix("---\n"))
    puts "wrote #{OUTPUT}: #{output.size} cops"
  end
end

GenerateRubocopConfig.run if __FILE__ == $PROGRAM_NAME
